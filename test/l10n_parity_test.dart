  test('EN ve TR anahtar kümeleri eşit ve 1025 anahtar kapsanıyor', () {
    final en = enStrings(AppLocalizationsEn());
    final tr = trStrings(AppLocalizationsTr());
    final enMethods = enMethodStrings(AppLocalizationsEn());
    final trMethods = trMethodStrings(AppLocalizationsTr());

    expect(en.length, 844);
    expect(tr.length, 844);
    expect(enMethods.length, 181);
    expect(trMethods.length, 181);
    expect(en.keys.toSet(), tr.keys.toSet());
    expect(enMethods.keys.toSet(), trMethods.keys.toSet());
    // Getter ve metot anahtarları çakışmaz; toplam soyut anahtar sayısı.
    expect(en.keys.toSet().intersection(enMethods.keys.toSet()), isEmpty);
    expect(en.length + enMethods.length, 1025);
    expect(allowedIdentical.difference({...en.keys, ...enMethods.keys}), isEmpty);
    expect(conditionalMethods.difference(enMethods.keys.toSet()), isEmpty);
  });

  test('her anahtarın iki dilde de boş olmayan karşılığı var', () {
    final en = enStrings(AppLocalizationsEn());
    final tr = trStrings(AppLocalizationsTr());
    final enMethods = enMethodStrings(AppLocalizationsEn());
    final trMethods = trMethodStrings(AppLocalizationsTr());

    for (final key in en.keys) {
      expect(en[key]!.trim(), isNotEmpty, reason: 'EN boş: $key');
      expect(tr[key]!.trim(), isNotEmpty, reason: 'TR boş: $key');
    }
    for (final key in enMethods.keys) {
      expect(enMethods[key]!.trim(), isNotEmpty, reason: 'EN boş: $key');
      expect(trMethods[key]!.trim(), isNotEmpty, reason: 'TR boş: $key');
    }
  });

  test('değişmezler dışında EN ve TR karşılıkları farklı', () {
    final en = {...enStrings(AppLocalizationsEn()), ...enMethodStrings(AppLocalizationsEn())};
    final tr = {...trStrings(AppLocalizationsTr()), ...trMethodStrings(AppLocalizationsTr())};
    // Koşullu metotlar metin karşılaştırmasının dışındadır.
    final comparedKeys = en.keys.toSet()..removeAll(conditionalMethods);

    for (final key in allowedIdentical) {
      if (conditionalMethods.contains(key)) continue;
      expect(en[key], tr[key], reason: 'değişmez kaydı: $key');
    }
    for (final key in comparedKeys) {
      if (allowedIdentical.contains(key)) continue;
      expect(en[key], isNot(tr[key]), reason: 'çevrilmemiş: $key');
    }
  });

